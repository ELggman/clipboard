"""应用级「数据修订号」：让页面**脏了才重查**。

背景（实测）：四个页面原先都在 `showEvent` 里无条件 `reload()`，于是在几个视图之间
快速来回切换时，每切一次都同步查一遍库 + 重建控件——时间线 5.4ms、收藏 4.3ms、
历史 4.2ms。数据其实一个字都没变，这些查询全是白做的。

做法：任何**数据库提交**都让修订号 +1（挂在 `database.engine.create_db_engine` 的
`commit` 事件上，见那里的注释，好处是绝不会漏掉某条写入路径）；页面在 `reload()` 结尾
记下当时的修订号，`showEvent` 里只有不一致才重查。

为什么用模块级计数器而不是 Qt 信号：调用点全在数据层，一行 `bump()` 比到处接信号简单，
也不会有 QObject 生命周期 / 悬挂连接的问题。

**失败模式是「保守」的**：万一某条写入路径没让修订号前进，页面只是没重查（显示旧数据）；
所以宁可多 bump，不可漏 bump。
"""
_revision = 0


def bump() -> None:
    """标记「数据变了」：所有页面下次显示时都要重查。"""
    global _revision
    _revision += 1


def revision() -> int:
    """当前修订号。页面装载后记下它，下次显示前比对是否要重查。"""
    return _revision
